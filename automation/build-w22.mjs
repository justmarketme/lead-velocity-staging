#!/usr/bin/env node
// Generates automation/W22.json: W22 Alerts, lean (18 Oct 2026, Jono: "n8n failures and workflow signals, 24 h dedupe,
// WhatsApp to me via the Twilio sender plus email via the SortMyCover relay. No ops schema.").
//   node automation/build-w22.mjs
// Logic: automation/lib/w22.mjs (tests: automation/tests/W22.test.mjs). The full design (ops schema, DND, escalation ladder,
// threshold sweep, probes) is in git history before this commit; it needed tables the CRM does not have.
// Env: OPS_ALERT_EMAIL, OPS_WHATSAPP_JONATHAN, OPS_WHATSAPP_KG (optional), TWILIO_CONTENT_SIDS.ops_alert (WhatsApp waits for it),
// LINDI_RELAY_TOKEN (smc-email-send), SUPABASE_FUNCTIONS_URL (optional). Sends honour DRY_RUN_SENDS.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const HERE = dirname(fileURLToPath(import.meta.url));
const { gateSenders } = createRequire(import.meta.url)('./lib/egress-gate.cjs');
let seq = 0;
const node = (name, type, typeVersion, position, parameters, extra = {}) => ({ id: `w22n${String(++seq).padStart(2, '0')}`, name, type: `n8n-nodes-base.${type}`, typeVersion, position, parameters, ...extra });
const ifTrue = (name, pos, expr) => node(name, 'if', 2, pos, { conditions: { options: { caseSensitive: true, leftValue: '', typeValidation: 'strict' }, combinator: 'and',
  conditions: [{ id: 'c1', leftValue: `={{ String(${expr}) }}`, rightValue: 'true', operator: { type: 'string', operation: 'equals' } }] }, options: {} });
const c = {};
const link = (from, to, out = 0) => { const x = (c[from] ||= { main: [] }); while (x.main.length <= out) x.main.push([]); x.main[out].push({ node: to, type: 'main', index: 0 }); };

const PLAN = 'Plan alerts (w22: normalise, 24 h dedupe, plan)';
const EMAIL = 'Email alert (smc-email-send)';
const n = [];
n.push(node('Sticky: read me', 'stickyNote', 1, [-460, -340], { width: 720, height: 300, content:
  '## W22 Alerts (lean, 18 Oct 2026)\n' +
  'In: the n8n Error Trigger (every SMC workflow names smc-w22 as its error workflow) and signals from other workflows (Execute Workflow; contract in W22.md).\n' +
  'Each signal becomes at most ONE alert per 24 h (signal_key|scope|severity, kept in this workflow\'s static data).\n' +
  'Out: email to OPS_ALERT_EMAIL through smc-email-send (SortMyCover <hello@sortmycover.co.za>), every alert; WhatsApp ops_alert to OPS_WHATSAPP_JONATHAN (+ OPS_WHATSAPP_KG) through smc-whatsapp-send for red alerts, once TWILIO_CONTENT_SIDS has ops_alert.\n' +
  'Red = a lead or booking workflow failed (W01-W07, W09, W10, W15, W28, WhatsApp Send, Email Verify) or a red producer signal. Amber = email only.\n' +
  'Logic: automation/lib/w22.mjs. Generated by automation/build-w22.mjs; do not hand-edit.' }));
n.push(node('Any workflow failed', 'errorTrigger', 1, [-460, 120], {}));
n.push(node('Signal from another workflow', 'executeWorkflowTrigger', 1.1, [-460, -60], { inputSource: 'passthrough' }));
n.push(node(PLAN, 'code', 2, [-200, 40], { mode: 'runOnceForAllItems', jsCode:
`const L = require('lv-automation').w22;
// 24-h dedupe in this workflow's static data (no ops schema): one alert per signal_key|scope|severity per day.
const sd = $getWorkflowStaticData('global');
const now = Date.now();
const env = { OPS_ALERT_EMAIL: $env.OPS_ALERT_EMAIL, OPS_WHATSAPP_JONATHAN: $env.OPS_WHATSAPP_JONATHAN, OPS_WHATSAPP_KG: $env.OPS_WHATSAPP_KG, TWILIO_CONTENT_SIDS: $env.TWILIO_CONTENT_SIDS };
const out = [];
for (const it of $input.all()) {
  const s = L.normalise(it.json || {}, new Date(now).toISOString());
  if (!s) continue;
  const d = L.dedupe(sd.sent || {}, L.dedupeKey(s), now);
  sd.sent = d.sent;
  if (!d.send) continue;
  for (const x of L.plan(s, env, now)) out.push({ json: x });
}
return out;` }));
n.push(ifTrue('Email?', [60, -60], "$json.channel === 'email'"));
n.push(node(EMAIL, 'httpRequest', 4.2, [320, -60], {
  method: 'POST', url: "={{ ($env.SUPABASE_FUNCTIONS_URL || 'https://cmsylaupctrbsvzrgzwy.supabase.co/functions/v1') + '/smc-email-send' }}",
  sendHeaders: true, headerParameters: { parameters: [{ name: 'Authorization', value: '=Bearer {{ $env.LINDI_RELAY_TOKEN }}' }, { name: 'Idempotency-Key', value: "={{ $json.relay.idempotency_key || '' }}" }] },
  sendBody: true, specifyBody: 'json', jsonBody: '={{ JSON.stringify($json.relay.body) }}',
  options: { timeout: 15000, response: { response: { fullResponse: true, neverError: true } } } }, { onError: 'continueRegularOutput' }));
n.push(ifTrue('WhatsApp?', [60, 140], "$json.channel === 'whatsapp'"));
n.push(node('SUB input (WhatsApp alert)', 'code', 2, [320, 140], { mode: 'runOnceForEachItem', jsCode: '// smc-whatsapp-send applies DRY_RUN_SENDS, the allow-list and the Twilio Content SID (TWILIO_CONTENT_SIDS.ops_alert).\nreturn { json: $json.send };' }));
n.push(node('Send WhatsApp alert (smc-whatsapp-send)', 'executeWorkflow', 1.2, [560, 140],
  { source: 'database', workflowId: { __rl: true, mode: 'id', value: 'smc-whatsapp-send', cachedResultName: 'WhatsApp Send' }, options: { waitForSubWorkflow: false } }, { onError: 'continueRegularOutput' }));

link('Any workflow failed', PLAN);
link('Signal from another workflow', PLAN);
link(PLAN, 'Email?');
link(PLAN, 'WhatsApp?');
link('Email?', EMAIL, 0);
link('WhatsApp?', 'SUB input (WhatsApp alert)', 0);
link('SUB input (WhatsApp alert)', 'Send WhatsApp alert (smc-whatsapp-send)');

const wf = gateSenders({ id: 'smc-w22', name: 'W22 Alerts', nodes: n, connections: c, active: false,
  settings: { executionOrder: 'v1', timezone: 'Africa/Johannesburg', saveDataSuccessExecution: 'all', saveDataErrorExecution: 'all', saveManualExecutions: true, callerPolicy: 'workflowsFromSameOwner' },
  pinData: {}, tags: [{ name: 'ops' }, { name: 'alerts' }], meta: { notes: 'Generated by automation/build-w22.mjs; logic automation/lib/w22.mjs; do not hand-edit.' } });
writeFileSync(join(HERE, 'W22.json'), JSON.stringify(wf, null, 2) + '\n');
console.log('wrote automation/W22.json', wf.nodes.length, 'nodes');
